const dictionaries: Record<Lang, Dict> = { en, fr, es };

export const LANGUAGE_NAMES: Record<Lang, string> = {
  en: 'English',
  fr: 'Français',
  es: 'Español',
};

export type TFunction = (key: string, vars?: Record<string, string | number>) => string;

interface I18nValue {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: TFunction;
}

const I18nContext = createContext<I18nValue | null>(null);

function interpolate(template: string, vars?: Record<string, string | number>): string {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name) =>
    name in vars ? String(vars[name]) : match
  );
}

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(getStoredLang);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    storeLang(next);
  }, []);

  const t = useCallback<TFunction>(
    (key, vars) => interpolate(dictionaries[lang][key] ?? dictionaries.en[key] ?? key, vars),
    [lang]
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error('useI18n must be used inside LanguageProvider');
  return value;
}

// Grade labels: English uses ordinals; French/Spanish read naturally as "grade N".
export function useGradeLabel(): (grade: string) => string {
  const { lang } = useI18n();
  return (grade: string) => {
    if (lang === 'fr') return `niveau ${grade}`;
    if (lang === 'es') return `grado ${grade}`;
    return `${String(grade) === '3' ? '3rd' : `${grade}th`} grade`;
  };
}
